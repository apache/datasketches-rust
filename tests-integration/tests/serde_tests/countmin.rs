#[test]
fn v2_reads_and_writes_the_published_image() {
    // TCK discussion #18, section 7.4: update(1, 10), update(9, 810), update("apple", 5).
    let words: [u64; 21] = [
        0x0000_0000_0012_0202,
        0x0093_cc02_0000_0009,
        825,
        810,
        0,
        0,
        0,
        5,
        0,
        10,
        0,
        0,
        0,
        5,
        810,
        0,
        0,
        0,
        0,
        10,
        0,
    ];
    let bytes: Vec<u8> = words.into_iter().flat_map(u64::to_le_bytes).collect();
    let mut sketch = CountMinSketch::<i64>::new_v2(2, 9).unwrap();
    let mut empty = bytes[..16].to_vec();
    empty[3] = 1;
    assert_eq!(sketch.serialize(), empty);
    assert_eq!(CountMinSketch::<i64>::deserialize(&empty).unwrap(), sketch);

    sketch.update_with_weight(1i64, 10);
    sketch.update_with_weight(9i64, 810);
    sketch.update_bytes_with_weight(b"apple", 5);
    assert_eq!(sketch.serialize(), bytes);

    let mut restored = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
    assert_eq!(restored, sketch);
    assert_eq!(restored.estimate(1u64), 10);
    assert_eq!(restored.estimate(natural_extend::from_i8(9)), 810);
    assert_eq!(restored.estimate_bytes(b"apple"), 5);
    restored.update_bytes_with_weight(b"apple", -2);
    assert_eq!(restored.estimate(raw_bytes::from_str("apple")), 3);
    assert_eq!(restored.total_weight(), 827);
    sketch.merge(&restored).unwrap();
    assert_eq!(sketch.estimate(raw_bytes::from_str("apple")), 8);
    assert_eq!(sketch.total_weight(), 1652);
}

#[test]
fn v2_matches_published_string_and_signed_integer_buckets() {
    fn check<I: Hash>(item: I, expected: [usize; 3]) {
        let mut sketch = CountMinSketch::<i64>::new_v2(3, 1000).unwrap();
        sketch.update_with_weight(&item, 7);
        let bytes = sketch.serialize();
        for (row, bucket) in expected.into_iter().enumerate() {
            let row_start = 24 + row * 1000 * 8;
            let counts: Vec<(usize, i64)> = bytes[row_start..row_start + 1000 * 8]
                .chunks_exact(8)
                .map(|bytes| i64::from_le_bytes(bytes.try_into().unwrap()))
                .enumerate()
                .filter(|(_, count)| *count != 0)
                .collect();
            assert_eq!(counts, [(bucket, 7)]);
        }
        let restored = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
        assert_eq!(restored.estimate(item), 7);
    }

    // Values computed with DataSketches Java XxHash64 in TCK discussion #18, section 7.3.
    check(-1i64, [256, 641, 308]);
    check(i64::MIN, [951, 0, 298]);
    check(raw_bytes::from_str("apple"), [130, 747, 144]);
    check(raw_bytes::from_str("été"), [806, 491, 163]);
    check(raw_bytes::from_slice(b"apple"), [130, 747, 144]);
    check(raw_bytes::from_slice("été".as_bytes()), [806, 491, 163]);
}

