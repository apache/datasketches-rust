fn sketch_snapshot<T: CountMinValue>(sketch: &CountMinSketch<T>) -> (u8, u32, u64, T, Vec<u8>) {
    (
        sketch.num_hashes(),
        sketch.num_buckets(),
        sketch.seed(),
        sketch.total_weight(),
        sketch.serialize(),
    )
}

fn words_to_bytes<const N: usize>(words: [u64; N]) -> Vec<u8> {
    words.into_iter().flat_map(u64::to_le_bytes).collect()
}

#[test]
fn v2_reads_and_writes_the_published_image() {
    // TCK discussion #18, section 7.4: update(1, 10), update(9, 810), update("apple", 5).
    let bytes = words_to_bytes([
        0x0000_0000_0012_0202,
        0x0093_cc02_0000_0009,
        825,
        810,
        0,
        0,
        0,
        5,
        0,
        10,
        0,
        0,
        0,
        5,
        810,
        0,
        0,
        0,
        0,
        10,
        0,
    ]);
    let mut sketch = CountMinSketch::<i64>::new(2, 9).unwrap();
    let mut empty = bytes[..16].to_vec();
    empty[3] = 1;
    assert_eq!(sketch.serialize(), empty);
    assert_eq!(
        sketch_snapshot(&CountMinSketch::<i64>::deserialize(&empty).unwrap()),
        sketch_snapshot(&sketch)
    );

    sketch.update_with_weight(1i64, 10);
    sketch.update_with_weight(9i64, 810);
    sketch.update_with_weight(raw_bytes::from_str("apple"), 5);
    assert_eq!(sketch.serialize(), bytes);

    let mut restored = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
    assert_eq!(sketch_snapshot(&restored), sketch_snapshot(&sketch));
    assert_eq!(restored.estimate(1u64), 10);
    assert_eq!(restored.estimate(natural_extend::from_i8(9)), 810);
    assert_eq!(restored.estimate(raw_bytes::from_str("apple")), 5);
    restored.update_with_weight(raw_bytes::from_str("apple"), -2);
    assert_eq!(restored.estimate(raw_bytes::from_str("apple")), 3);
    assert_eq!(restored.total_weight(), 827);
    sketch.merge(&restored).unwrap();
    assert_eq!(sketch.estimate(raw_bytes::from_str("apple")), 8);
    assert_eq!(sketch.total_weight(), 1652);
}

#[test]
fn v2_matches_known_bucket_vectors() {
    fn check<I: Hash>(item: I, seed: u64, expected: [usize; 3]) {
        let mut sketch = CountMinSketch::<i64>::with_seed(3, 1000, seed).unwrap();
        sketch.update_with_weight(&item, 7);
        let bytes = sketch.serialize();
        for (row, bucket) in expected.into_iter().enumerate() {
            let row_start = 24 + row * 1000 * 8;
            let counts: Vec<(usize, i64)> = bytes[row_start..row_start + 1000 * 8]
                .chunks_exact(8)
                .map(|bytes| i64::from_le_bytes(bytes.try_into().unwrap()))
                .enumerate()
                .filter(|(_, count)| *count != 0)
                .collect();
            assert_eq!(counts, [(bucket, 7)], "seed {seed}, row {row}");
        }
    }

    // Java XxHash64 vectors from TCK discussion #18, section 7.3.
    check(-1i64, 9001, [256, 641, 308]);
    check(natural_extend::from_i8(-1), 9001, [256, 641, 308]);
    check(i64::MIN, 9001, [951, 0, 298]);
    check(raw_bytes::from_str("apple"), 9001, [130, 747, 144]);
    check(
        raw_bytes::from_slice("été".as_bytes()),
        9001,
        [806, 491, 163],
    );

    // Independently computed with XXH64 over little-endian u64 inputs.
    check(1u64, 9001, [185, 898, 4]);
    check(9u64, 9001, [490, 217, 440]);
    check(natural_extend::from_u16(9), 9001, [490, 217, 440]);
    check(1u64, 42, [468, 459, 696]);
    check(9u64, 42, [841, 428, 322]);
}

#[test]
fn legacy_image_preserves_wrappers_and_custom_hash_inputs() {
    #[derive(Hash)]
    struct Key(u64);

    // Generated by Rust v0.6.0: raw_bytes("apple", 5), natural_extend(-1i8, 7),
    // Key(42, 11), and raw_bytes("", 13), with two rows and nine buckets.
    let bytes = words_to_bytes([
        0x0000_0000_0012_0102,
        0x0093_cc02_0000_0009,
        36,
        7,
        0,
        16,
        0,
        13,
        0,
        0,
        0,
        0,
        11,
        0,
        12,
        0,
        0,
        0,
        13,
        0,
        0,
    ]);
    let mut sketch = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
    assert_eq!(sketch.serialize(), bytes);

    let restored = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
    assert_eq!(restored.estimate(raw_bytes::from_str("apple")), 12);
    assert_eq!(restored.estimate(natural_extend::from_i8(-1)), 7);
    assert_eq!(restored.estimate(Key(42)), 11);
    assert_eq!(restored.estimate(raw_bytes::from_str("")), 13);

    sketch.merge(&restored).unwrap();
    sketch.update(Key(42));
    assert_eq!(sketch.estimate(Key(42)), 23);
    assert_eq!(sketch.total_weight(), 73);
    assert_eq!(sketch.serialize()[1], 1);
    assert_eq!(
        sketch_snapshot(&CountMinSketch::<i64>::deserialize(&sketch.serialize()).unwrap()),
        sketch_snapshot(&sketch)
    );
}

#[test]
fn v2_row_limit_does_not_reject_legacy_images() {
    for rows in [128, 255] {
        let mut bytes = CountMinSketch::<i64>::new(1, 3).unwrap().serialize();
        bytes[12] = rows;
        assert_eq!(
            CountMinSketch::<i64>::deserialize(&bytes)
                .unwrap_err()
                .kind(),
            ErrorKind::InvalidData
        );
        bytes[1] = 1;
        let legacy = CountMinSketch::<i64>::deserialize(&bytes).unwrap();
        assert_eq!(legacy.num_hashes(), rows);
        assert_eq!(legacy.serialize(), bytes);
    }
}

// Generated by CountMinSketch v0.5.0 with one row, five buckets, seed 123, and key 1 at weight 10.
fn rust_v1_custom_seed_image() -> Vec<u8> {
    words_to_bytes([
        0x0000_0000_0012_0102,
        0x0005_b601_0000_0005,
        10,
        0,
        0,
        0,
        0,
        10,
    ])
}

#[test]
fn legacy_rust_v1_image_preserves_queries_updates_and_merges() {
    let image = rust_v1_custom_seed_image();
    let mut sketch = CountMinSketch::<u64>::deserialize_with_seed(&image, 123).unwrap();
    assert_eq!(sketch.total_weight(), 10);
    assert_eq!(sketch.estimate(1u64), 10);
    assert_eq!(sketch.serialize(), image);

    sketch.update_with_weight(1u64, 5);
    assert_eq!(sketch.total_weight(), 15);
    assert_eq!(sketch.estimate(1u64), 15);
    assert_eq!(sketch.serialize()[1], 1);

    let mut merged = CountMinSketch::<u64>::deserialize_with_seed(&image, 123).unwrap();
    merged.merge(&sketch).unwrap();
    assert_eq!(merged.total_weight(), 25);
    assert_eq!(merged.estimate(1u64), 25);
}

#[test]
fn rejects_merge_across_serial_versions() {
    let legacy =
        CountMinSketch::<u64>::deserialize_with_seed(&rust_v1_custom_seed_image(), 123).unwrap();
    let mut current = CountMinSketch::<u64>::with_seed(1, 5, 123).unwrap();
    current.update_with_weight(1u64, 10);
    let before = current.clone();

    assert_eq!(
        current.merge(&legacy).unwrap_err().kind(),
        ErrorKind::InvalidArgument
    );
    assert_eq!(sketch_snapshot(&current), sketch_snapshot(&before));
}

#[test]
fn rejects_unknown_serial_version() {
    let mut bytes = CountMinSketch::<u64>::new(1, 5).unwrap().serialize();
    bytes[1] = 3;
    let error = CountMinSketch::<u64>::deserialize(&bytes).unwrap_err();
    assert_eq!(error.kind(), ErrorKind::InvalidData);
    assert_that!(
        error.message(),
        contains_substring("expected 1 or 2, got 3")
    );
}

#[test]
fn rejects_weights_that_cannot_bound_counter_arithmetic() {
    let mut sketch = CountMinSketch::<i8>::new(2, 8).unwrap();
    sketch.update("x");
    let bytes = sketch.serialize();
    for (total, count) in [(-1i64, 0i64), (1, 2), (1, -2), (127, -128)] {
        let mut corrupt = bytes.clone();
        corrupt[16..24].copy_from_slice(&total.to_le_bytes());
        corrupt[24..32].copy_from_slice(&count.to_le_bytes());
        assert_eq!(
            CountMinSketch::<i8>::deserialize(&corrupt)
                .unwrap_err()
                .kind(),
            ErrorKind::InvalidData
        );
    }
}

// This helper validates binary format compatibility (deserialize + byte round-trip) for
// version 1 datasketches-cpp and datasketches-go CountMin snapshots. It intentionally does not
// assert estimate equivalence because version 1 row-seed derivation differs across implementations.
fn assert_v1_snapshot(
    dir: &str,
    filename: &str,
    seed: u64,
    expected_num_hashes: u8,
    expected_num_buckets: u32,
    expected_total_weight: u64,
) {
    let path = serialization_test_data(dir, filename);
    let bytes = fs::read(&path).unwrap();

    let sketch = CountMinSketch::<u64>::deserialize_with_seed(&bytes, seed).unwrap();

    assert_eq!(sketch.num_hashes(), expected_num_hashes);
    assert_eq!(sketch.num_buckets(), expected_num_buckets);
    assert_eq!(sketch.seed(), seed);
    assert_eq!(sketch.total_weight(), expected_total_weight);
    assert_eq!(sketch.is_empty(), expected_total_weight == 0);

    let roundtrip = sketch.serialize();
    assert_eq!(roundtrip, bytes, "round-trip bytes differ for {filename}");
}

