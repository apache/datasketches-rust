#[test]
fn test_custom_kll_value_roundtrip() {
    let mut sketch = KllSketch::<Record>::new(64).unwrap();
    for key in 0..1_000 {
        sketch.update(Record {
            key,
            category: (key % 7) as u16,
        });
    }

    let decoded = KllSketch::<Record>::deserialize(&sketch.serialize()).unwrap();

    assert_eq!(decoded, sketch);
    assert_eq!(decoded.n(), 1_000);
    assert_eq!(decoded.num_retained(), sketch.num_retained());
}

#[test]
fn test_rejects_truncated_or_trailing_data() {
    let mut sketch = KllSketch::<KllFloat<f32>>::default();
    for value in 0..1_000 {
        sketch.update(KllFloat::<f32>::new(value as f32).unwrap());
    }
    let bytes = sketch.serialize();

    for length in [7, 15, bytes.len() - 1] {
        assert!(KllSketch::<KllFloat<f32>>::deserialize(&bytes[..length]).is_err());
    }

    let mut with_trailing_data = bytes;
    with_trailing_data.push(0);
    assert!(KllSketch::<KllFloat<f32>>::deserialize(&with_trailing_data).is_err());
}

#[test]
fn test_string_value_reports_the_truncated_field_and_byte_counts() {
    let mut input = SketchSlice::new(&[5, 0, 0, 0, b'a']);

    let error = String::deserialize(&mut input).unwrap_err();

    assert_eq!(error.kind(), ErrorKind::InvalidData);
    assert_eq!(
        error.message(),
        "insufficient data (KLL string payload): expected 5 bytes, got 1"
    );
}
