//! KLL Sketch Serialization Compatibility Tests
//!
//! These tests verify binary compatibility with Apache DataSketches implementations:
//! - Java (datasketches-java)
//! - C++ (datasketches-cpp)
//! - Go (datasketches-go)
//!
//! Test data is generated by the reference implementations and stored in:
//! `tests/serde_tests/{java_generated_files,cpp_generated_files}/`.

use std::cmp::Ordering;
use std::fs;
use std::path::PathBuf;

use datasketches::codec::SketchBytes;
use datasketches::codec::SketchSlice;
use datasketches::error::Error;
use datasketches::error::ErrorKind;
use datasketches::kll::KllFloat;
use datasketches::kll::KllSketch;
use datasketches::kll::KllValue;

use crate::serialization_test_data;

const DEFAULT_K: u16 = 200;

#[derive(Debug, Clone, PartialEq, Eq)]
struct NumericString(String);

impl Ord for NumericString {
    fn cmp(&self, other: &Self) -> Ordering {
        parse_string_value(&self.0).cmp(&parse_string_value(&other.0))
    }
}

impl PartialOrd for NumericString {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl KllValue for NumericString {
    const MIN_SERIALIZED_SIZE: usize = String::MIN_SERIALIZED_SIZE;

    fn serialized_size(value: &Self) -> usize {
        String::serialized_size(&value.0)
    }

    fn serialize(value: &Self, bytes: &mut SketchBytes) {
        String::serialize(&value.0, bytes);
    }

    fn deserialize(input: &mut SketchSlice<'_>) -> Result<Self, Error> {
        String::deserialize(input).map(Self)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
struct Record {
    key: i64,
    category: u16,
}

impl KllValue for Record {
    const MIN_SERIALIZED_SIZE: usize = 10;

    fn serialized_size(_value: &Self) -> usize {
        10
    }

    fn serialize(value: &Self, bytes: &mut SketchBytes) {
        bytes.write_i64_le(value.key);
        bytes.write_u16_le(value.category);
    }

    fn deserialize(input: &mut SketchSlice<'_>) -> Result<Self, Error> {
        let key = input
            .read_i64_le()
            .map_err(|_| Error::new(ErrorKind::InvalidData, "missing record key"))?;
        let category = input
            .read_u16_le()
            .map_err(|_| Error::new(ErrorKind::InvalidData, "missing record category"))?;
        Ok(Self { key, category })
    }
}

fn test_f32_file(path: PathBuf, expected_n: usize) {
    let bytes = fs::read(&path).unwrap();
    let sketch = KllSketch::<KllFloat<f32>>::deserialize(&bytes)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()));

    assert_eq!(sketch.k(), DEFAULT_K, "wrong k in {}", path.display());
    assert_eq!(
        sketch.n() as usize,
        expected_n,
        "wrong n in {}",
        path.display()
    );
    assert_eq!(
        sketch.is_estimation_mode(),
        expected_n > DEFAULT_K as usize,
        "wrong estimation mode in {}",
        path.display()
    );
    assert_eq!(
        sketch.is_empty(),
        expected_n == 0,
        "wrong empty flag in {}",
        path.display()
    );

    if expected_n == 0 {
        assert!(sketch.min_item().is_none(), "min should be None");
        assert!(sketch.max_item().is_none(), "max should be None");
    } else {
        assert_eq!(
            sketch.min_item().map(|value| **value),
            Some(1.0),
            "min item mismatch in {}",
            path.display()
        );
        assert_eq!(
            sketch.max_item().map(|value| **value),
            Some(expected_n as f32),
            "max item mismatch in {}",
            path.display()
        );
    }

    assert_eq!(sketch.serialize(), bytes, "roundtrip: {}", path.display());
}

